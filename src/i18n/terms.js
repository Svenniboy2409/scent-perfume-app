const TERMS = { nl: NL }

/** Display name of a vocabulary value (`kind` = season, occasion, gender, …). */
export function translateTerm(lang, kind, value) {
  return TERMS[lang]?.[kind]?.[value] ?? value
}

/** Translate a value whose kind isn't known (e.g. a search suggestion). */
export function translateAnyTerm(lang, value) {
  const table = TERMS[lang]
  if (!table) return value
  for (const kind of ['season', 'occasion', 'gender', 'time', 'accord', 'note']) {
    if (table[kind][value]) return table[kind][value]
  }
  return value
}

/** Every Dutch name for one kind — used to make the search index bilingual. */
export function termsFor(lang, kind) {
  return TERMS[lang]?.[kind] ?? {}
}
